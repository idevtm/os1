char ps2_console_character(const Ps2Modifiers& modifiers, uint8_t key)
{
    if(key >= sizeof(plain_map) / sizeof(plain_map[0]))
        return 0;
    if(modifiers.keypad)
        if(const unsigned navigation = navigation_key(key))
            return static_cast<char>(navigation);
    if(modifiers.shift && key == 0x0f)
        return OS1_CONSOLE_KEY_BACKTAB;
    if(modifiers.control && key == 0x39)
        return OS1_CONSOLE_KEY_COMPLETE;
    if(modifiers.control && key == 0x2e)
        return 3;
    if(modifiers.control && key == 0x20)
        return 4;
    if(key == 0x1c)
        return '\n';
    if(modifiers.keypad && key == 0x35)
        return '/';
    const uint16_t keysym = modifiers.shift ? shift_map[key] : plain_map[key];
    const auto value = static_cast<uint8_t>(keysym);
    switch(keysym >> 8)
    {
        case 0xf0:  // Latin.
        case 0xfb:  // Letter.
            return value >= 0x20 || value == '\t' || value == 0x1b ? char(value) : 0;
        case 0xf3:  // Keypad.
        {
            constexpr char keypad[] = "0123456789+-*";
            if(value == 0x10)
                return '.';
            return value < sizeof(keypad) - 1 ? keypad[value] : 0;
        }
        default:
            return 0;
    }
}
